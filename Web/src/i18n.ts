export type TranslationKey = keyof (typeof translations)["en"];

export const text = (language: Language, key: TranslationKey): string =>
  translations[language][key];

export const statusText = (language: Language, status: SolverStatus): string => {
  const values: Record<SolverStatus, [string, string]> = {
    RETURN: ["RETURN", "确认返回"],
    RETURN_UNCERTAIN: ["RETURN UNCERTAIN", "返回结论不确定"],
    IMPACT: ["IMPACT", "撞击月表"],
    ESCAPE: ["ESCAPE", "逃逸"],
    NO_RETURN_WITHIN_WINDOW: ["NO RETURN WITHIN WINDOW", "时间窗内未返回"],
    NUMERICAL_FAILURE: ["NUMERICAL FAILURE", "数值计算失败"],
  };
  return values[status][language === "en" ? 0 : 1];
};

